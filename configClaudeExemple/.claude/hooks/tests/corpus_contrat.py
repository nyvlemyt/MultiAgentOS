def _git(id: str, commande: str, attendu: str, regle: str, source: str, **kw: object) -> Cas:
    return Cas(id, "git", "Bash", {"command": commande}, attendu, regle, source, **kw)  # type: ignore[arg-type]


def _perim(id: str, commande: str, attendu: str, regle: str, source: str, **kw: object) -> Cas:
    return Cas(id, "perimetre", "Bash", {"command": commande}, attendu, regle, source, **kw)  # type: ignore[arg-type]


def _ps(id: str, commande: str, attendu: str, regle: str, source: str, **kw: object) -> Cas:
    return Cas(id, "perimetre", "PowerShell", {"command": commande}, attendu, regle, source, **kw)  # type: ignore[arg-type]


def _outil(id: str, outil: str, chemin: str, attendu: str, regle: str, source: str, **kw: object) -> Cas:
    cle = "notebook_path" if outil == "NotebookEdit" else "file_path"
    return Cas(id, "perimetre", outil, {cle: chemin}, attendu, regle, source, **kw)  # type: ignore[arg-type]


def _donnees(id: str, outil: str, entree: dict, attendu: str, regle: str, source: str, **kw: object) -> Cas:
    return Cas(id, "donnees", outil, entree, attendu, regle, source, **kw)  # type: ignore[arg-type]


